/**
 * V8's number conversions as the runtime links them (#1516): V8 12.4's src/numbers/conversions.cc
 * (Number's toString, toFixed, toExponential, toPrecision and radix strings; StringToDouble) over
 * src/base/numbers (dtoa, strtod, bignum), with src/strings/char-predicates.cc and
 * src/utils/allocation.cc, shaved from the files that define each function (by symbol, as the
 * linker resolves them), and the C library they call shaved from musl. `scripts/shave-v8-numbers.ts`
 * writes it as `atoms/v8-numbers.ts`; a test checks that file is what this gives. Needs clang.
 */
import { fileURLToPath } from "node:url";
import type { ShavedAtomSource } from "../atoms/shave-math.js";
import type { StaticDef } from "../raise-c.js";
import { shaveCFiles } from "./c-files.js";
import { shaveMusl } from "./c-musl.js";
import { atomLibrarySource } from "./v8-bigint-library.js";

const here = (p: string): string => fileURLToPath(new URL(p, import.meta.url));

/** V8 as Node v22 builds it: its features (Node's), for x86-64 Linux. */
export const V8_DEFINES = [
  "-DV8_TARGET_ARCH_X64",
  "-DV8_HAVE_TARGET_OS",
  "-DV8_TARGET_OS_LINUX",
  "-DV8_ENABLE_WEBASSEMBLY",
  "-DV8_INTL_SUPPORT",
  "-DV8_ENABLE_JAVASCRIPT_PROMISE_HOOKS",
  "-DV8_ENABLE_CONTINUATION_PRESERVED_EMBEDDER_DATA",
  "-DV8_ENABLE_SEEDED_ARRAY_INDEX_HASH",
];

/** The clang arguments for V8's files: its sources, its generated headers (vendor/v8/gen), ICU. */
export function v8Args(): string[] {
  const v8 = here("../../vendor/v8");
  const icu = here("../../vendor/node/deps/icu-small/source");
  return [
    "-std=c++20",
    ...V8_DEFINES,
    `-I${v8}`,
    `-I${v8}/include`,
    `-I${v8}/gen`,
    `-I${icu}/common`,
    `-I${icu}/i18n`,
    `-I${v8}/third_party/abseil-cpp`,
    "-Wno-everything",
  ];
}

/** The functions the runtime calls, by symbol. */
export const V8_NUMBERS_ROOTS = {
  doubleToCString: "_ZN2v88internal15DoubleToCStringEdNS_4base6VectorIcEE",
  intToCString: "_ZN2v88internal12IntToCStringEiNS_4base6VectorIcEE",
  doubleToRadixCString: "_ZN2v88internal20DoubleToRadixCStringEdi",
  doubleToFixedCString: "_ZN2v88internal20DoubleToFixedCStringEdi",
  doubleToExponentialCString: "_ZN2v88internal26DoubleToExponentialCStringEdi",
  doubleToPrecisionCString: "_ZN2v88internal24DoubleToPrecisionCStringEdi",
  stringToDouble: "_ZN2v88internal14StringToDoubleENS_4base6VectorIKtEEid",
} as const;

export function shaveV8NumbersLibrary(): {
  readonly atoms: ReadonlyMap<string, ShavedAtomSource>;
  readonly statics: ReadonlyMap<string, StaticDef>;
  readonly refused: readonly string[];
  readonly externals: readonly string[];
} {
  const v8 = here("../../vendor/v8/");
  const icu = here("../../vendor/node/deps/icu-small/source/");
  const files = [
    ...[
      "bignum",
      "cached-powers",
      "diy-fp",
      "bignum-dtoa",
      "fast-dtoa",
      "fixed-dtoa",
      "dtoa",
      "strtod",
    ].map((f) => `${v8}src/base/numbers/${f}.cc`),
    `${v8}src/numbers/conversions.cc`,
    `${v8}src/strings/char-predicates.cc`,
    `${v8}src/utils/allocation.cc`,
    `${icu}common/uchar.cpp`,
  ];
  const v8Files = shaveCFiles(
    files,
    Object.values(V8_NUMBERS_ROOTS),
    [...v8Args(), "-DU_COMMON_IMPLEMENTATION"],
    "clang++",
  );
  // What no file defines: the C library's, from musl; V8's fatal paths (an abort's report, out of
  // memory) are left as their names.
  const libc = shaveMusl(v8Files.externals.filter((x) => !x.startsWith("_Z") && !/^V8_/.test(x)));
  const sorted = <T>(m: Iterable<[string, T]>): Map<string, T> =>
    new Map([...m].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  const units = [...v8Files.units, ...libc.units];
  return {
    atoms: sorted([...libc.atoms, ...v8Files.atoms]),
    statics: sorted(units.flatMap((u) => [...u.statics])),
    refused: [...v8Files.refused, ...libc.refused, ...libc.missing],
    externals: v8Files.externals.filter((x) => x.startsWith("_Z") || /^V8_/.test(x)),
  };
}

/** The library as the TypeScript of `atoms/v8-numbers.ts`. */
export function v8NumbersLibrarySource(lib: ReturnType<typeof shaveV8NumbersLibrary>): string {
  return atomLibrarySource(lib, {
    header: `// GENERATED by scripts/shave-v8-numbers.ts from vendor/v8 (V8 12.4.254.21: src/numbers/conversions.cc,
// src/base/numbers, src/strings/char-predicates.cc, src/utils/allocation.cc), ICU's uchar.cpp
// (vendor/node/deps/icu-small) and vendor/musl (musl 1.2.5). Do not edit: shave again. (#1516)
// Left as names (V8's fatal paths, never taken but to abort): ${lib.externals.join(", ")}.`,
    atoms: "V8_NUMBERS_ATOM_SOURCES",
    atomsDoc: "V8's number conversions' atoms, shaved, by symbol (the C library's by name).",
    statics: "V8_NUMBERS_STATICS",
    staticsDoc: "Their statics (V8's and ICU's constants and tables, musl's state), by key.",
  });
}
