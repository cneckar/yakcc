/**
 * V8's BigInt library as the runtime links it (#1516): V8 12.4's `src/bigint` shaved
 * (`atoms/shave-v8.ts`), and the C library it calls (memcpy, memset, memmove, abort) shaved from
 * musl, with their statics. `scripts/shave-v8-bigint.ts` writes it as `atoms/v8-bigint.ts`; a test
 * checks that file is what this gives. Needs clang.
 */
import type { ShavedAtomSource } from "../atoms/shave-math.js";
import { shaveV8BigInt } from "../atoms/shave-v8.js";
import type { StaticDef } from "../raise-c.js";
import { shaveMusl } from "./c-musl.js";

export function shaveV8BigIntLibrary(): {
  readonly atoms: ReadonlyMap<string, ShavedAtomSource>;
  readonly statics: ReadonlyMap<string, StaticDef>;
  readonly refused: readonly string[];
} {
  const unit = shaveV8BigInt();
  const libc = shaveMusl(["memcpy", "memset", "memmove", "abort"]);
  const sorted = <T>(m: Iterable<[string, T]>): Map<string, T> =>
    new Map([...m].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  return {
    atoms: sorted([...libc.atoms, ...unit.atoms]),
    statics: sorted([...libc.units.flatMap((u) => [...u.statics]), ...unit.statics]),
    refused: [...libc.refused, ...[...unit.refused].map(([k, r]) => `${k}: ${r}`), ...libc.missing],
  };
}

/** A shaved library as the TypeScript of a generated `atoms/*.ts`: its atoms and statics. */
export function atomLibrarySource(
  lib: {
    readonly atoms: ReadonlyMap<string, ShavedAtomSource>;
    readonly statics: ReadonlyMap<string, StaticDef>;
  },
  o: { header: string; atoms: string; atomsDoc: string; statics: string; staticsDoc: string },
): string {
  const value = (v: unknown): string =>
    JSON.stringify(v, (_k, x) => (typeof x === "bigint" ? `__big:${x}` : x)).replace(
      /"__big:(-?[0-9]+)"/g,
      "$1n",
    );
  const atoms = [...lib.atoms]
    .map(
      ([n, a]) =>
        `  ${JSON.stringify(n)}: { source: ${JSON.stringify(a.source)}, externals: ${JSON.stringify(a.externals)} },`,
    )
    .join("\n");
  const statics = [...lib.statics]
    .map(([k, d]) => `  ${JSON.stringify(k)}: ${value(d)},`)
    .join("\n");
  return `// SPDX-License-Identifier: Apache-2.0
${o.header}
import type { StaticDef } from "../raise-c.js";
import type { ShavedAtomSource } from "./shave-math.js";

/** ${o.atomsDoc} */
export const ${o.atoms}: Readonly<Record<string, ShavedAtomSource>> = {
${atoms}
};

/** ${o.staticsDoc} */
export const ${o.statics}: Readonly<Record<string, StaticDef>> = {
${statics}
};
`;
}

/** The library as the TypeScript of `atoms/v8-bigint.ts`. */
export function v8BigIntLibrarySource(lib: ReturnType<typeof shaveV8BigIntLibrary>): string {
  return atomLibrarySource(lib, {
    header: `// GENERATED by scripts/shave-v8-bigint.ts from vendor/v8/src/bigint (V8 12.4.254.21, through
// src/atoms/v8/bigint.cc) and vendor/musl (memcpy, memset, memmove, abort; musl 1.2.5). Do not
// edit: shave again. (#1516)`,
    atoms: "V8_BIGINT_ATOM_SOURCES",
    atomsDoc: "V8's BigInt library's atoms, shaved, with the C library's they call: by name.",
    statics: "V8_BIGINT_STATICS",
    staticsDoc: "Their statics (V8's constants, the Platform's vtable, musl's state), by key.",
  });
}
