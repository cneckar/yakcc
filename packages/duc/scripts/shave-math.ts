// Write src/atoms/math.ts: Math's atoms shaved from V8's ieee754.cc and musl's scalbn.c (#1362).
// Run from packages/duc: `tsx scripts/shave-math.ts`, then format with biome. Needs clang.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { shaveMathAtoms } from "../src/atoms/shave-math.js";

const { atoms, refused } = shaveMathAtoms();
if (refused.size > 0) throw new Error(`refused: ${[...refused].join("; ")}`);
const body = [...atoms]
  .map(
    ([name, a]) =>
      `  ${JSON.stringify(name)}: { source: ${JSON.stringify(a.source)}, externals: ${JSON.stringify(a.externals)} },`,
  )
  .join("\n");
const out = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/shave-math.ts from vendor/v8/src/base/ieee754.cc (V8 12.4.254.21) and
// vendor/musl/src/math/scalbn.c (musl 1.2.5). Do not edit: shave again. (#1362)
import type { ShavedAtomSource } from "./shave-math.js";

/** \`Math\`'s atoms, shaved: the TypeScript the lifter reads, by name. */
export const MATH_ATOM_SOURCES: Readonly<Record<string, ShavedAtomSource>> = {
${body}
};
`;
writeFileSync(fileURLToPath(new URL("../src/atoms/math.ts", import.meta.url)), out);
console.log(`${atoms.size} atoms`);
