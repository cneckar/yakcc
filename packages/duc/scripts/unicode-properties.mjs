/** The ranges of the code points a pattern (with u) matches, one at a time. */
function ranges(pattern) {
  const re = new RegExp(`^${pattern}$`, "u");
  const out = [];
  let lo = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const hit = c <= 0x10ffff && re.test(String.fromCodePoint(c));
    if (hit && lo < 0) lo = c;
    if (!hit && lo >= 0) {
      out.push([lo, c - 1]);
      lo = -1;
    }
  }
  return out;
}
/** A table's entry: each range as base-36 "start" or "start-end", comma-separated. */
const encode = (rs) =>
  rs.map(([a, b]) => (a === b ? a.toString(36) : `${a.toString(36)}-${b.toString(36)}`)).join(",");

const entries = []; // [canonical name, names, encoded]
for (const [short, long] of GENERAL)
  entries.push([
    `gc=${short}`,
    [
      short,
      long,
      `gc=${short}`,
      `gc=${long}`,
      `General_Category=${short}`,
      `General_Category=${long}`,
    ],
    encode(ranges(`\\p{${short}}`)),
  ]);
for (const [name, alias] of BINARY)
  entries.push([name, alias ? [name, alias] : [name], encode(ranges(`\\p{${name}}`))]);
for (const [name, alias] of SCRIPTS) {
  const names = [];
  for (const n of alias ? [name, alias] : [name]) names.push(`sc=${n}`, `Script=${n}`);
  entries.push([`sc=${name}`, names, encode(ranges(`\\p{Script=${name}}`))]);
  const xnames = [];
  for (const n of alias ? [name, alias] : [name]) xnames.push(`scx=${n}`, `Script_Extensions=${n}`);
  entries.push([`scx=${name}`, xnames, encode(ranges(`\\p{Script_Extensions=${name}}`))]);
}
const table = entries.map(([c, , e]) => `  ${JSON.stringify(c)}: ${JSON.stringify(e)},`).join("\n");
const names = entries
  .flatMap(([c, ns]) => ns.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(c)},`))
  .join("\n");
const out = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/unicode-properties.mjs from Node ${process.versions.node}'s RegExp (Unicode
// ${process.versions.unicode}). Do not edit: generate again. (#1331)

/** Each property's code points: ranges in base 36, "start" or "start-end", comma-separated. */
export const UNICODE_PROPERTY_RANGES: Readonly<Record<string, string>> = {
${table}
};

/** Each name a \\\\p{…} may use (a value, its long name, \`gc=\`/\`sc=\`/\`scx=\` forms), to its property. */
export const UNICODE_PROPERTY_NAMES: Readonly<Record<string, string>> = {
${names}
};

/** The Unicode version the table is of. */
export const UNICODE_VERSION = ${JSON.stringify(process.versions.unicode)};
`;
writeFileSync(new URL("../src/unicode-properties.ts", import.meta.url), out);
console.log(`${entries.length} properties, ${out.length} bytes`);
